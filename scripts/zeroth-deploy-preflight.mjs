#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const args = new Set(process.argv.slice(2));
const allowPlaceholders = args.has("--allow-placeholders");
const skipBuild = args.has("--skip-build");
const withStartupCheck = args.has("--with-startup-check");
const configPath = path.join(root, "wrangler.zeroth.jsonc");
const config = readConfig();
const d1DatabaseName = config?.d1_databases?.find((entry) => entry.binding === "ZEROTH_DB")
  ?.database_name || "wavey-id-zeroth";
const expectedClientCount = 5;

const checks = [];

runCommand("config_template", "node", [
  "scripts/verify-zeroth-config.mjs",
  "--allow-placeholders",
], {
  hint: "The Zeroth Wrangler config or client seed SQL is structurally invalid.",
});

if (!allowPlaceholders) {
  runCommand("config_deploy", "node", ["scripts/verify-zeroth-config.mjs"], {
    hint: "Replace placeholder D1/provider client IDs before treating this as a production deployment.",
  });
}

runCommand("d1_schema_and_clients", npxCommand(), [
  "wrangler",
  "d1",
  "execute",
  d1DatabaseName,
  "--remote",
  "--config",
  "wrangler.zeroth.jsonc",
  "--command",
  "SELECT COUNT(*) AS client_count FROM zeroth_clients; SELECT COUNT(*) AS allowed_email_domain_column_count FROM pragma_table_info('zeroth_clients') WHERE name = 'allowed_email_domains_json'; SELECT COUNT(*) AS provider_nonce_column_count FROM pragma_table_info('zeroth_auth_transactions') WHERE name = 'provider_nonce'; SELECT COUNT(*) AS local_credentials_table_count FROM sqlite_master WHERE type = 'table' AND name = 'zeroth_local_credentials'; SELECT COUNT(*) AS magic_links_table_count FROM sqlite_master WHERE type = 'table' AND name = 'zeroth_magic_links'",
], {
  hint: "Create the D1 database, patch wrangler.zeroth.jsonc, then run npm run zeroth:d1:init.",
  validate: (result) => {
    const clientCount = d1ClientCount(result.stdout);
    if (clientCount === null) {
      return "could not read client_count from D1 response";
    }
    if (clientCount < expectedClientCount) {
      return `expected at least ${expectedClientCount} seeded clients, found ${clientCount}`;
    }
    const policyColumnCount = d1ScalarValue(result.stdout, "allowed_email_domain_column_count");
    if (policyColumnCount !== 1) {
      return "missing zeroth_clients.allowed_email_domains_json compatibility column";
    }
    const providerNonceColumnCount = d1ScalarValue(result.stdout, "provider_nonce_column_count");
    if (providerNonceColumnCount !== 1) {
      return "missing zeroth_auth_transactions.provider_nonce compatibility column";
    }
    const localCredentialsTableCount = d1ScalarValue(result.stdout, "local_credentials_table_count");
    if (localCredentialsTableCount !== 1) {
      return "missing zeroth_local_credentials table";
    }
    const magicLinksTableCount = d1ScalarValue(result.stdout, "magic_links_table_count");
    if (magicLinksTableCount !== 1) {
      return "missing zeroth_magic_links table";
    }
    return null;
  },
});

runCommand("worker_api_read", npxCommand(), [
  "wrangler",
  "deployments",
  "list",
  "--config",
  "wrangler.zeroth.jsonc",
], {
  hint: "The Cloudflare token needs Workers Scripts read access for the configured account and Worker.",
});

runCommand("worker_secrets_read", npxCommand(), [
  "wrangler",
  "secret",
  "list",
  "--config",
  "wrangler.zeroth.jsonc",
], {
  hint: "The Cloudflare token needs Workers Scripts read/edit access before npm run zeroth:secrets can upload secrets.",
});

if (!skipBuild) {
  runCommand("worker_build_package", npmCommand(), [
    "run",
    "--silent",
    "zeroth:deploy:dry-run",
  ], {
    hint: "The Zeroth Worker did not compile or package cleanly for Cloudflare.",
  });
}

if (withStartupCheck) {
  removeStartupProfile();
  runCommand("worker_startup_profile", npxCommand(), [
    "wrangler",
    "check",
    "startup",
    "--config",
    "wrangler.zeroth.jsonc",
  ], {
    hint: "Wrangler startup analysis did not complete; inspect Worker startup before deploying to the free-tier route.",
  });
  runCommand("worker_startup_budget", "node", [
    "scripts/zeroth-startup-profile.mjs",
    "--max-cpu-ms=10",
  ], {
    hint: "Zeroth Worker startup exceeded the local 10 ms CPU-profile guardrail.",
  });
}

const failed = checks.filter((check) => !check.ok);
const summary = {
  ok: failed.length === 0,
  allow_placeholders: allowPlaceholders,
  skipped_build: skipBuild,
  with_startup_check: withStartupCheck,
  checks,
};

console.log(JSON.stringify(summary, null, 2));

if (failed.length > 0) {
  process.exit(1);
}

function readConfig() {
  try {
    return JSON.parse(fs.readFileSync(configPath, "utf8"));
  } catch {
    return null;
  }
}

function removeStartupProfile() {
  try {
    fs.unlinkSync(path.join(root, "worker-startup.cpuprofile"));
  } catch {
    // The file is generated by `wrangler check startup`; absence is expected.
  }
}

function runCommand(name, command, commandArgs, { hint, validate }) {
  const started = Date.now();
  const result = spawnSync(command, commandArgs, {
    cwd: root,
    encoding: "utf8",
    env: {
      ...process.env,
      CI: process.env.CI || "1",
    },
  });
  const durationMs = Date.now() - started;
  const validationError = result.status === 0 && validate ? validate(result) : null;
  checks.push({
    name,
    ok: result.status === 0 && !validationError,
    status: result.status,
    duration_ms: durationMs,
    command: [command, ...commandArgs].join(" "),
    hint,
    validation_error: validationError,
    diagnostic: commandDiagnostic(result),
    stdout_tail: tail(result.stdout),
    stderr_tail: tail(result.stderr),
  });
}

function commandDiagnostic(result) {
  const output = stripAnsi(`${result.stdout || ""}\n${result.stderr || ""}`);
  if (!output.includes("Authentication error [code: 10000]")) {
    return null;
  }
  if (output.includes("/workers/scripts/") || output.includes("/workers/services/")) {
    return {
      class: "cloudflare_workers_auth",
      cloudflare_code: 10000,
      required_permissions: [
        "Workers Scripts:Read",
        "Workers Scripts:Edit",
      ],
      account_id: config?.account_id || null,
      worker_name: config?.name || null,
      description:
        "Cloudflare accepted the token for some account APIs but rejected Workers Scripts APIs for this Worker.",
    };
  }
  return {
    class: "cloudflare_auth",
    cloudflare_code: 10000,
    account_id: config?.account_id || null,
    description: "Cloudflare rejected this API request for the configured token.",
  };
}

function d1ClientCount(stdout) {
  return d1ScalarValue(stdout, "client_count");
}

function d1ScalarValue(stdout, fieldName) {
  const parsed = jsonFromWranglerOutput(stdout);
  if (!Array.isArray(parsed)) {
    return null;
  }
  for (const item of parsed) {
    const rows = Array.isArray(item?.results) ? item.results : [];
    for (const row of rows) {
      if (Number.isFinite(Number(row?.[fieldName]))) {
        return Number(row[fieldName]);
      }
    }
  }
  return null;
}

function jsonFromWranglerOutput(stdout) {
  const value = stripAnsi(String(stdout || ""));
  const start = value.indexOf("[");
  const end = value.lastIndexOf("]");
  if (start === -1 || end === -1 || end <= start) {
    return null;
  }
  try {
    return JSON.parse(value.slice(start, end + 1));
  } catch {
    return null;
  }
}

function tail(value) {
  const lines = stripAnsi(String(value || "")).trim().split(/\r?\n/).filter(Boolean);
  return lines.slice(-20);
}

function stripAnsi(value) {
  return value.replace(/\u001b\[[0-9;]*m/g, "");
}

function npxCommand() {
  return process.platform === "win32" ? "npx.cmd" : "npx";
}

function npmCommand() {
  return process.platform === "win32" ? "npm.cmd" : "npm";
}
